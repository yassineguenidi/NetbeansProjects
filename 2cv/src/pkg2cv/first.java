    public String createChaine(){
        chaine = "Le nom: "+name.getText()+"\n";
        chaine += "Le prenom: "+surname.getText()+"\n";
        chaine += "Email: "+email.getText()+"\n";
        chaine += "NumTel: "+numtel.getText()+"\n";
        chaine += "-Stages effectués:\n";
        
        try{
            if(model.getRowCount()!=0){
                
                for(int i=0;i<model.getRowCount();i++){
                    chaine+= "- Lieu stage: "+model.getValueAt(i, 0).toString()+
                    "\t periode: "+model.getValueAt(i, 1).toString()+
                    "\t Tache effectué: "+model.getValueAt(i, 2).toString()+"\n";
                }
            }
        }catch(Exception e1){
            System.out.println("stageTable is Empty!");
        }
        try{
            if(model2.getRowCount()!=0){
                chaine += "-Projets:\n";
                for(int i=0;i<model2.getRowCount();i++){
                    chaine+= "- Lieu stage: "+model2.getValueAt(i, 0).toString()+
                    "\t periode: "+model2.getValueAt(i, 1).toString()+"\n";
                }    
            }
        }catch(Exception e2){
            System.out.println("projectTable is Empty!");
        }
        try{
            if(model3.getRowCount()!=0){
                chaine += "-Competences:\n";
                for(int i=0;i<model3.getRowCount();i++){
                    chaine+= "- Competence: "+model3.getValueAt(i, 0).toString()+"\n";   
                }   
            }
        }catch(Exception e){
             System.out.println("competences is Empty!");
        }
        
        finally{
            return chaine;
        }
        
        
    }
