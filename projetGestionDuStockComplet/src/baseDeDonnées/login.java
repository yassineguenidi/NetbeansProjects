    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
     rs= db.querySelectAll("utilisateur","username='" +txtuser.getText()
             +"' and password='"+txtpassword.getText()+"'");

     try{
         while(rs.next()){
             username = rs.getString("username");
             password= rs.getString("password");
             hak=rs.getString("type");
         }
         
     }catch(SQLException ex){
         Logger.getLogger(login.class.getName()).log(Level.SEVERE,null,ex);
     }
     if(username==null && password==null){
         JOptionPane.showMessageDialog(null,"le nom utilisiteur ou le password est incorrect ");
         
     }else{
         if(hak.equals("directeur")){
             Principale h = new Principale() ;
             h.setVisible(true);
             this.dispose();
                
             
         }else{
             Cachier k = new Cachier();
             k.setVisible(true);
             this.dispose();
         }
     }
    }//GEN-LAST:event_jButton2ActionPerformed

