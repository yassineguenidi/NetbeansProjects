    private void ajouterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ajouterActionPerformed
         String id =idVente.getText();
         String designation =designationVente.getText();
         String pas =prixAchatVente.getText();
         String qtte =quantiteVente.getText();
         String pvv = prixVenteVente.getText();
       
         String requete = "insert into vente(id,designation,prixachat,quantite,prixvente)VALUES('"
                 +id+"','"+designation+"','"+pas+"','"+qtte+"','"+pvv+"')";
        
         try{
             stm.executeUpdate(requete);
             JOptionPane.showMessageDialog(null,"le produit à vendre est ajouté correctement !");
             idVente.setText("");
             designationVente.setText("");
             prixAchatVente.setText("");
             quantiteVente.setText("");
             prixVenteVente.setText("");
             afficher();
         }catch(Exception ex){JOptionPane.showMessageDialog(null, ex.getMessage());}
    }//GEN-LAST:event_ajouterActionPerformed

    private void supprimerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_supprimerActionPerformed
        try{
      
           if(JOptionPane.showConfirmDialog(null, "attention vous allez supprimer un produit !","suppression",
                 JOptionPane.YES_NO_OPTION )==JOptionPane.YES_OPTION  ){
               
                if(idVente.getText().length()!=0){
                    
                   stm.executeUpdate("DELETE FROM vente where id="+idVente.getText());
                   idVente.setText("");
                   designationVente.setText("");
                   prixAchatVente.setText("");
                   quantiteVente.setText("");
                   prixVenteVente.setText("");
                   afficher();
                   }else{
                         JOptionPane.showMessageDialog(null,"Veuillez remplir le champs id !");
                        }
           }
      }catch(Exception ex){JOptionPane.showMessageDialog(null,"erreur de suppression !"+ ex.getMessage());}
    }//GEN-LAST:event_supprimerActionPerformed

