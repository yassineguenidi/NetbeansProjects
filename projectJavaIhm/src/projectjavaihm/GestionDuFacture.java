    private void supprimerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_supprimerActionPerformed
         try{
      
           if(JOptionPane.showConfirmDialog(null, "attention vous allez supprimer une facture !","suppression",
                 JOptionPane.YES_NO_OPTION )==JOptionPane.YES_OPTION  ){
               
                if(idFacture.getText().length()!=0){
                    
                   stm.executeUpdate("DELETE FROM facture where id="+idFacture.getText());
                   idFacture.setText("");
                   nomFacture.setText("");
                   prenomFacture.setText("");
                   montapFacture.setText("");
                   montavFacture.setText("");
                   
                   afficher();
                   }else{
                         JOptionPane.showMessageDialog(null,"Veuillez remplir le champs id !");
                        }
           }
      }catch(Exception ex){JOptionPane.showMessageDialog(null,"erreur de suppression !"+ ex.getMessage());}
    }//GEN-LAST:event_supprimerActionPerformed

