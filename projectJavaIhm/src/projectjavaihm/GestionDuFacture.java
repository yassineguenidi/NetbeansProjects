    private void ajouterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ajouterActionPerformed
         String id =idFacture.getText();
         String nom =nomFacture.getText();
         String prenom =prenomFacture.getText();
         String montap =montapFacture.getText();
         String montav =montavFacture.getText();
         
        
       
         String requete = "insert into facture (id,nom,prenom,montap,montav)VALUES("
                 + "'"+id+"','"+nom+"','"+prenom+"','"+montap+"','"+montav+"')";
        
         try{
             stm.executeUpdate(requete);
             JOptionPane.showMessageDialog(null,"la facture est ajoutée correctement !");
             idFacture.setText("");
             nomFacture.setText("");
             prenomFacture.setText("");
             montapFacture.setText("");
             montavFacture.setText("");
             
             afficher();
         }catch(Exception ex){JOptionPane.showMessageDialog(null, ex.getMessage());}
    }//GEN-LAST:event_ajouterActionPerformed

