    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
      
         String id =txtid.getText();
         String nom =txtnom.getText();
         String prenom =txtprenom.getText();
         String branche =txtbranche.getSelectedItem().toString();
         String note =txtnote.getText();
         String requete = "insert into etude (id,nom,prenom,branche,note)VALUES('"
                 +id+"','"+nom+"','"+prenom+"','"+branche+"','"+note+"')";
        
         try{
             stm.executeUpdate(requete);
             JOptionPane.showMessageDialog(null,"l'etudiant est ajouté correctement !");
             txtid.setText("");
             txtnom.setText("");
             txtprenom.setText("");
             txtbranche.setSelectedItem("");
             txtnote.setText("");
             afficher();
         }catch(Exception ex){JOptionPane.showMessageDialog(null, ex.getMessage());}
          
        
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        try{
            if(JOptionPane.showConfirmDialog(null, "confirmer la modification","modification",
                 JOptionPane.YES_NO_OPTION )==JOptionPane.YES_OPTION  ){
                
                stm.executeUpdate("UPDATE etude  SET nom ='"+txtnom.getText()+"',prenom='"+txtprenom.getText()
                                  +"', branche='"+txtbranche.getSelectedItem().toString()+"',note='"+txtnote.getText()+
                                   "'WHERE id= "+txtid.getText());
                txtid.setText("");
                txtnom.setText("");
                txtprenom.setText("");
                txtbranche.setSelectedItem("");
                txtnote.setText("");
                afficher();
            }
        }catch(Exception ex){JOptionPane.showMessageDialog(null, "erreur de modification "+ex.getMessage());
        System.out.println(ex);}
    }//GEN-LAST:event_jButton4ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
      try{
      
           if(JOptionPane.showConfirmDialog(null, "attention vous allez supprimer un etudiant !","suppression",
                 JOptionPane.YES_NO_OPTION )==JOptionPane.YES_OPTION  ){
               
                if(txtid.getText().length()!=0){
                    
                   stm.executeUpdate("DELETE FROM etude where id="+txtid.getText());
                   txtid.setText("");
                   txtnom.setText("");
                   txtprenom.setText("");
                   txtbranche.setSelectedItem("");
                   txtnote.setText("");
                   afficher();
                   }else{
                         JOptionPane.showMessageDialog(null,"Veuillez remplir le champs id !");
                        }
           }
      }catch(Exception ex){JOptionPane.showMessageDialog(null,"erreur de suppression !"+ ex.getMessage());}
      
    }//GEN-LAST:event_jButton3ActionPerformed

