    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
     try{
        if(cincase.getText().equals("")||nomcase.getText().equals("")||prenomcase.getText().equals("")||agecase.getText().equals("")
                      ||datecase.getText().equals("")){
        JOptionPane.showMessageDialog(this, "validez votre saisie !");
    }                                      
        else {
            String data[] = {cincase.getText(),nomcase.getText(),prenomcase.getText(),agecase.getText(),datecase.getText()};
            DefaultTableModel tableModel = (DefaultTableModel)tablecase.getModel();
            tableModel.addRow(data);
            JOptionPane.showMessageDialog(this,  "vous avez bien ajouté l'etudiant ");
            cincase.setText("");
            nomcase.setText("");           
            prenomcase.setText("");
            agecase.setText("");
            datecase.setText("");                     
        }
     }
     catch (Exception e)
           {JOptionPane.showMessageDialog(null,"veuuillez verifier votre saisie");}
    }//GEN-LAST:event_jButton1ActionPerformed

